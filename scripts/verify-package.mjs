import {execFileSync} from 'node:child_process';
import {mkdtemp,mkdir,readFile,stat} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const pkg=JSON.parse(await readFile('package.json','utf8'));
const archive=resolve(`dist-package/${pkg.name}-${pkg.version}.tgz`);
const expected=(await readFile(archive+'.sha256','utf8')).split(/\s/)[0];
assert.equal(createHash('sha256').update(await readFile(archive)).digest('hex'),expected);
await mkdir('.vite',{recursive:true});const root=await mkdtemp(resolve('.vite/package-verify-'));
execFileSync('tar',['-xzf',archive,'-C',root]);
const installed=join(root,'package');const commands=new Map();
const {default:plugin}=await import(pathToFileURL(join(installed,'dist/main.js')).href);
const dispose=await plugin.activate({commands:{register:(id,handler)=>commands.set(id,handler)}});
assert.deepEqual([...commands.keys()].sort(),pkg.biglazycat.contributes.commands.map(c=>c.id).sort());
await dispose();
for(const file of ['dist/ui/index.html','dist/ui/runtime/typesetting/typst_ts_web_compiler_bg.wasm','dist/ui/runtime/typesetting/NotoSerifSC_400Regular.ttf','dist/ui/runtime/typesetting/NotoSerifSC_700Bold.ttf','dist/ui/runtime/typesetting/NotoEmoji_400Regular.ttf','dist/ui/runtime/typesetting/NotoSansMono_400Regular.ttf','dist/ui/runtime/fonts/LXGWWenKai-Regular.woff2','dist/ui/runtime/fonts/LXGWWenKai-Medium.woff2','dist/ui/runtime/pdfjs/worker.mjs','dist/ui/runtime/pdfjs/pdf.worker.mjs'])assert.ok((await stat(join(installed,file))).size>0,file);
await assert.rejects(stat(join(installed,'node_modules')),{code:'ENOENT'});
console.log(JSON.stringify({archive,bytes:(await stat(archive)).size,sha256:expected,commands:commands.size,standaloneBackend:true},null,2));
